def lesson(title, subject, intro, rules, example, trap, rows):
    lid = len(lessons) + 1
    lessons.append(dict(id=lid, title=title, subject=subject, intro=intro, rules=rules, example=example, trap=trap))
    for n, (prompt, answer, other, explain) in enumerate(rows):
        choices = [str(answer)] + [str(x) for x in other]
        assert len(choices) == 4 and len(set(choices)) == 4, (title, prompt)
        questions.append(dict(id=f'{lid:02}-{n+1:02}', lesson=lid, subject=subject,
            level='기초' if n < 3 else '응용', kind='자체 제작', prompt=prompt,
            choices=choices, correct=0, explanation=explain))

